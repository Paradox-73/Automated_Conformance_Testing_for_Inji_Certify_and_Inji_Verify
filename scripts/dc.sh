#!/usr/bin/env bash
# shellcheck source-path=SCRIPTDIR
#
# The one way to run Docker Compose for the harness. Arguments go to "docker compose" unchanged:
#
#   bash scripts/dc.sh --profile verify up -d --wait
#   bash scripts/dc.sh --profile verify pull
#   bash scripts/dc.sh run --rm probe -sS https://verify.inji.test:18451/v1/verify/actuator/health
#   bash scripts/dc.sh config -q
#
# What it adds to a plain "docker compose" call:
# - the project file at the repository root and the project name ($HARNESS_COMPOSE_PROJECT, default ps01-harness),
#   so it works from any working directory;
# - --env-file $HARNESS_RUN_DIR/env.local. On first use the file is created with random passwords for the
#   harness containers; a later version that needs a new password appends it and keeps the existing ones (a
#   database volume keeps the password it was created with). The file stays out of git;
# - the folders the containers mount ($HARNESS_RUN_DIR/pki and /reports), created as the calling user so that
#   containers running as that user can write them on Linux;
# - HARNESS_RUN_DIR as a native path and Git Bash path rewriting turned off, so bind mounts work on Windows;
# - HARNESS_UID and HARNESS_GID, the user the pki-init and runner containers run as (files they write stay
#   owned by the calling user on Linux);
# - "--profile *" for "down" when no profile is named, so "bash scripts/dc.sh down -v" stops every service;
# - each file of HARNESS_COMPOSE_FILES (comma-separated, relative to the repository root or absolute) as a further
#   --file after docker-compose.yml, for overrides such as demo/regression.compose.yml.
#
# Settings: HARNESS_RUN_DIR, HARNESS_COMPOSE_PROJECT (see scripts/lib/common.sh). Image overrides such as
# VERIFY_IMAGE are read from the environment or from env.local.

set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

# Passwords generated into env.local. Every name is a compose variable in docker-compose.yml (now or in a planned
# version), so a later compose version finds its password already present.
readonly HARNESS_ENV_GENERATED=(VERIFY_DB_PASSWORD CERTIFY_DB_PASSWORD CERTIFY_KEYSTORE_PASSWORD
  MINIO_ROOT_PASSWORD VERIFY_KEYSTORE_PASSWORD)

# random_secret: 32 lower-case hex characters (128 bits) from the kernel's random source.
random_secret() {
  local hex
  hex=$(od -An -N16 -tx1 /dev/urandom | tr -d ' \n')
  [[ $hex =~ ^[0-9a-f]{32}$ ]] || die "cannot read random bytes from /dev/urandom"
  printf '%s\n' "$hex"
}

# ensure_env_file FILE: create FILE, or append the generated secrets it lacks. Existing values are never changed.
# A lock folder next to the file keeps two parallel first calls from writing different passwords.
ensure_env_file() {
  local file=$1 lock=$1.lock name missing=() tries=0
  until mkdir -- "$lock" 2>/dev/null; do
    tries=$((tries + 1))
    ((tries <= 100)) || die "timed out waiting for $lock (remove it if no other dc.sh is running)"
    sleep 0.1
  done
  # shellcheck disable=SC2064 # expand $lock now: the trap runs after this function's locals are gone
  trap "rmdir -- '$lock' 2>/dev/null || true" EXIT

  for name in "${HARNESS_ENV_GENERATED[@]}"; do
    if [[ ! -f $file ]] || ! grep -q "^$name=" -- "$file"; then
      missing+=("$name")
    fi
  done
  if ((${#missing[@]})); then
    local tmp=$file.tmp.$$
    {
      if [[ -f $file ]]; then
        cat -- "$file"
      else
        printf '# Local passwords for the ps01-harness containers, generated by scripts/dc.sh on %s.\n' \
          "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        printf '# Read by docker compose as --env-file. Never commit this file. Delete it together with the\n'
        printf '# compose volumes (scripts/dc.sh down -v) to get new passwords.\n'
      fi
      for name in "${missing[@]}"; do
        printf '%s=%s\n' "$name" "$(random_secret)"
      done
    } >"$tmp"
    chmod 600 "$tmp"
    mv -f -- "$tmp" "$file"
    log_info "env.local: generated ${missing[*]} in $file"
  fi

  rmdir -- "$lock"
  trap - EXIT
}

# with_down_profiles ARGS...: the arguments for compose, with "--profile *" in front when the subcommand is "down"
# and no profile was named. A plain "down" leaves services that were started with a profile running, and a later
# "up" silently reuses that old stack. Only the subcommand counts: "run --rm runner sh -c down" is left alone.
with_down_profiles() {
  local arg expect_value=0 subcommand='' has_profile=0
  for arg in "$@"; do
    if ((expect_value)); then
      expect_value=0
      continue
    fi
    case $arg in
      --profile | --profile=*) has_profile=1 ;;&
      --profile | -f | --file | --env-file | -p | --project-name | --project-directory | --ansi | --progress | \
        --parallel) expect_value=1 ;;
      -*) ;;
      *)
        subcommand=$arg
        break
        ;;
    esac
  done
  if [[ $subcommand == down ]] && ((!has_profile)); then
    printf '%s\0' --profile '*' "$@"
  elif (($#)); then
    printf '%s\0' "$@"
  fi
}

main() {
  harness_require_cmd docker "install Docker with the Compose v2 plugin"
  [[ $HARNESS_COMPOSE_PROJECT == ps01-* ]] ||
    die "HARNESS_COMPOSE_PROJECT must start with ps01- (got $HARNESS_COMPOSE_PROJECT)" 2

  local run_dir
  run_dir=$(harness_run_dir)
  harness_run_dir pki >/dev/null
  harness_run_dir reports >/dev/null
  ensure_env_file "$run_dir/env.local"

  IFS=: read -r HARNESS_UID HARNESS_GID < <(harness_container_user)
  HARNESS_RUN_DIR=$(harness_native_path "$run_dir")
  export HARNESS_UID HARNESS_GID HARNESS_RUN_DIR

  local root args=() files=() extra
  root=$(harness_native_path "$HARNESS_ROOT")
  files=(--file "$root/docker-compose.yml")
  local -a extras=()
  IFS=, read -r -a extras <<<"${HARNESS_COMPOSE_FILES:-}"
  for extra in "${extras[@]}"; do
    [[ -n $extra ]] || continue
    [[ $extra == /* || $extra =~ ^[A-Za-z]: ]] || extra=$HARNESS_ROOT/$extra
    [[ -f $extra ]] || die "HARNESS_COMPOSE_FILES: no such file: $extra" 2
    files+=(--file "$(harness_native_path "$extra")")
  done
  mapfile -d '' -t args < <(with_down_profiles "$@")
  MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' exec docker compose \
    --project-name "$HARNESS_COMPOSE_PROJECT" \
    --project-directory "$root" \
    "${files[@]}" \
    --env-file "$HARNESS_RUN_DIR/env.local" \
    "${args[@]}"
}

main "$@"
